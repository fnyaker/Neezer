/// The namespace `ids.NS_TRACK` derives from on the server (a uuid5 of
/// `"deezer.com/neezer"` and `"track"`), as `trackkey.js` spells it.
pub const NS_TRACK: [u8; 16] = [
    0x34, 0x9c, 0x6f, 0x7c, 0x1d, 0x1f, 0x50, 0x8d, 0x85, 0x39, 0x91, 0x80, 0xc6, 0x6e, 0x5e, 0xf7,
];

/// A queue row's key: the row's UUID, or the uuid5 its row will have.
///
/// `id` is what the server calls the row (absent on a catalogue result that is
/// not in the library yet); `deezer_id` is the catalogue id. A non-numeric
/// `deezer_id` is already a UUID (an upload, a YouTube fallback row, a podcast
/// episode) and is kept as it is.
pub fn track_key(id: Option<&str>, deezer_id: Option<&str>) -> Option<String> {
    if let Some(id) = id.filter(|s| !s.is_empty()) {
        return Some(id.to_owned());
    }
    let deezer_id = deezer_id.filter(|s| !s.is_empty())?;
    if is_deezer_number(deezer_id) {
        Some(uuid5(&NS_TRACK, deezer_id))
    } else {
        Some(deezer_id.to_owned())
    }
}

/// An old stored key (a Deezer id) to the UUID it hashes to; anything else is
/// returned untouched (`trackkey.js#migrateKey`).
pub fn migrate_key(raw: &str) -> String {
    if is_deezer_number(raw) {
        uuid5(&NS_TRACK, raw)
    } else {
        raw.to_owned()
    }
}

/// What a request names the track by (`trackkey.js#trackRef`): the row's id when
/// there is one, else the Deezer id — the only form the server can still turn
/// into a row.
pub fn track_ref<'a>(id: Option<&'a str>, deezer_id: Option<&'a str>) -> Option<&'a str> {
    id.filter(|s| !s.is_empty())
        .or_else(|| deezer_id.filter(|s| !s.is_empty()))
}

/// `^[0-9]{1,20}$`, the shape `migrateKey` hashes.
fn is_deezer_number(text: &str) -> bool {
    !text.is_empty() && text.len() <= 20 && text.bytes().all(|b| b.is_ascii_digit())
}

/// Python's `uuid.uuid5(namespace, name)`, as text.
pub fn uuid5(namespace: &[u8; 16], name: &str) -> String {
    let mut data = Vec::with_capacity(16 + name.len());
    data.extend_from_slice(namespace);
    data.extend_from_slice(name.as_bytes());
    let mut hash = sha1(&data);
    hash[6] = (hash[6] & 0x0f) | 0x50; // version 5
    hash[8] = (hash[8] & 0x3f) | 0x80; // RFC 4122 variant
    let mut out = String::with_capacity(36);
    for (i, byte) in hash[..16].iter().enumerate() {
        if i == 4 || i == 6 || i == 8 || i == 10 {
            out.push('-');
        }
        out.push_str(&format!("{byte:02x}"));
    }
    out
}

/// RFC 3174 SHA-1, as 20 bytes. Here rather than in a dependency because the
/// crate is pure and this is the only hash it needs.
fn sha1(data: &[u8]) -> [u8; 20] {
    let mut state: [u32; 5] = [
        0x6745_2301,
        0xefcd_ab89,
        0x98ba_dcfe,
        0x1032_5476,
        0xc3d2_e1f0,
    ];
    let mut message = data.to_vec();
    let bit_len = (data.len() as u64).wrapping_mul(8);
    message.push(0x80);
    while message.len() % 64 != 56 {
        message.push(0);
    }
    message.extend_from_slice(&bit_len.to_be_bytes());

    let mut words = [0u32; 80];
    for chunk in message.as_chunks::<64>().0 {
        for (i, word) in words.iter_mut().take(16).enumerate() {
            *word = u32::from_be_bytes([
                chunk[4 * i],
                chunk[4 * i + 1],
                chunk[4 * i + 2],
                chunk[4 * i + 3],
            ]);
        }
        for i in 16..80 {
            words[i] = (words[i - 3] ^ words[i - 8] ^ words[i - 14] ^ words[i - 16]).rotate_left(1);
        }
        let (mut a, mut b, mut c, mut d, mut e) =
            (state[0], state[1], state[2], state[3], state[4]);
        for (i, word) in words.iter().enumerate() {
            let (f, k) = match i {
                0..=19 => ((b & c) | ((!b) & d), 0x5a82_7999),
                20..=39 => (b ^ c ^ d, 0x6ed9_eba1),
                40..=59 => ((b & c) | (b & d) | (c & d), 0x8f1b_bcdc),
                _ => (b ^ c ^ d, 0xca62_c1d6),
            };
            let t = a
                .rotate_left(5)
                .wrapping_add(f)
                .wrapping_add(e)
                .wrapping_add(k)
                .wrapping_add(*word);
            e = d;
            d = c;
            c = b.rotate_left(30);
            b = a;
            a = t;
        }
        state[0] = state[0].wrapping_add(a);
        state[1] = state[1].wrapping_add(b);
        state[2] = state[2].wrapping_add(c);
        state[3] = state[3].wrapping_add(d);
        state[4] = state[4].wrapping_add(e);
    }

    let mut out = [0u8; 20];
    for (i, word) in state.iter().enumerate() {
        out[4 * i..4 * i + 4].copy_from_slice(&word.to_be_bytes());
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sha1_matches_the_rfc_vectors() {
        // RFC 3174 section 7.3, plus the empty input every implementation pins.
        let hex = |bytes: [u8; 20]| bytes.iter().map(|b| format!("{b:02x}")).collect::<String>();
        assert_eq!(hex(sha1(b"")), "da39a3ee5e6b4b0d3255bfef95601890afd80709");
        assert_eq!(
            hex(sha1(b"abc")),
            "a9993e364706816aba3e25717850c26c9cd0d89d"
        );
        assert_eq!(
            hex(sha1(
                b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"
            )),
            "84983e441c3bd26ebaae4aa1f95129e5e54670f1"
        );
    }

    #[test]
    fn track_key_matches_the_servers_uuid5() {
        // Values produced by the SPA: `slimTrack` sends `trackKey(t).id`, and
        // tests/fixtures/commands.json carries the same two strings.
        assert_eq!(
            track_key(None, Some("3000001")).unwrap(),
            "21408a08-d175-53a4-a02d-733a7bc83812"
        );
        assert_eq!(
            track_key(None, Some("3135556")).unwrap(),
            uuid5(&NS_TRACK, "3135556")
        );
        // A row id wins, an upload/episode UUID is kept as it is, and nothing at
        // all has no key.
        assert_eq!(
            track_key(
                Some("3f7c1d2e-9a4b-5c6d-8e0f-1a2b3c4d5e6f"),
                Some("3135556")
            )
            .unwrap(),
            "3f7c1d2e-9a4b-5c6d-8e0f-1a2b3c4d5e6f"
        );
        assert_eq!(
            track_key(None, Some("11d1e3c8-1c93-4b6f-bf73-185fd2805cfc")).unwrap(),
            "11d1e3c8-1c93-4b6f-bf73-185fd2805cfc"
        );
        assert_eq!(track_key(None, None), None);
        assert_eq!(track_key(Some(""), Some("")), None);
    }

    #[test]
    fn migrate_key_hashes_only_deezer_numbers() {
        assert_eq!(migrate_key("3135556"), uuid5(&NS_TRACK, "3135556"));
        assert_eq!(migrate_key("not-a-number"), "not-a-number");
        assert_eq!(migrate_key(""), "");
    }

    #[test]
    fn track_ref_prefers_the_row_id() {
        assert_eq!(track_ref(Some("row"), Some("42")), Some("row"));
        assert_eq!(track_ref(None, Some("42")), Some("42"));
        assert_eq!(track_ref(Some(""), Some("42")), Some("42"));
        assert_eq!(track_ref(None, None), None);
    }
}
