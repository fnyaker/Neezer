//! The queue and the transport as a pure state machine, with the web player's
//! own rules.
//!
//! Owned by lot D4 (`docs/agents/desktop.md`): [`PlayerState::apply`] takes one
//! [`Command`] and the caller's monotonic clock, and returns the [`Effect`]s the
//! app must carry out. There is no I/O and no clock in here, so every rule is a
//! unit test and remote control maps 1:1 onto the SPA's
//! `webapp/src/lib/remote/commands.js`.
//!
//! # The seam
//!
//! ```text
//! UI / MPRIS / remote host ──Command──▶ PlayerState ──Effect──▶ app wiring
//!                                                       ├─ Load        → nz-audio engine (ladder.js quality)
//!                                                       ├─ PreloadNext → engine's second voice
//!                                                       ├─ ReportListen→ POST /api/listen
//!                                                       ├─ NeedMore    → flow/radio top-up
//!                                                       ├─ Persist     → nz-cache queue snapshot (off-main)
//!                                                       └─ Changed     → redraw
//! ```
//!
//! The effects come back in that order. A command that means nothing (a jump to
//! a row that no longer exists, a `next` on an empty queue) changes nothing and
//! returns no effects at all, so a caller can treat "no effects" as "refused".
//!
//! `now_ms` is the caller's clock in milliseconds. It is used for ONE thing, the
//! listen accounting ([`listen`]): the state is constant between two `apply`
//! calls, so the wall time since the previous one is playing time exactly when
//! the transport was playing — a paused desktop reports nothing, and a track
//! change reports what was actually heard (`Player.svelte#flushListen`).
//!
//! # Identity
//!
//! A queue row is keyed the way the SPA keys it (`webapp/src/lib/trackkey.js`):
//! the row's UUID when there is one, else the uuid5 of the Deezer id — the UUID
//! the row *will* have, because `ids.track_uuid` is deterministic on the server.
//! [`track_key`] is that function, ported (SHA-1/uuid5 included) so the desktop
//! never invents a second identity: a catalogue result and the row it becomes
//! are the same queue entry, which is what makes de-duplication, "un-shuffle"
//! and a remote `jump` by id agree with the browser.
//!
//! # The wire
//!
//! [`Command`] serialises to exactly the JSON a remote control sends
//! (`commands.js#commandFor`, plus the `seek` the controller posts itself), and
//! [`Entry`] to exactly `slimTrack`'s shape. That fixture is generated by the
//! JavaScript, not written by hand (`tests/fixtures/commands.json`,
//! `tests/wire.rs`).

