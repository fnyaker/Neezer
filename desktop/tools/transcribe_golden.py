#!/usr/bin/env python3
"""Write — or check — the golden files the Rust port is held to, using Python.

The Rust crate `desktop/crates/nz-transcribe` re-implements two functions the
server already runs: `neezer/transcribe/engine.py#normalize_segments` (what one
chunk of whisper output becomes) and `neezer/transcribe/sidecar.py` (the
`.transcript.json` and `.transcript.srt` on the data disk). A transcription made
on a laptop and one made on the server land in the same archive and the same
database, so "close enough" is not enough: the bytes must be identical.

This script is the oracle, and it is deliberately the Python side of the pair —
a fixture generated by the Rust code would only prove the Rust code agrees with
itself. It loads the two modules by PATH (not by package import) so it needs
neither Flask, nor the database, nor a virtualenv: they import nothing but the
standard library.

Each case becomes one directory under
`desktop/crates/nz-transcribe/tests/golden/<case>/`:

    case.json        the input: raw whisper items, the chunk's position and
                     length, the overlap, and the transcript's metadata
    segments.json    engine.normalize_segments(...) as compact JSON
    transcript.json  sidecar.dumps(sidecar.build(...))
    transcript.srt   sidecar.srt_bytes(...)

A case whose `sidecar` is null has no `transcript.*` (its lines alone are the
point). A case may carry `sidecar_segments`: the raw lines the document is built
from, when the sidecar's own cleaning — which differs from the engine's, because
a document written by the server may hold a tag — is what it exercises.

    python3 desktop/tools/transcribe_golden.py            # rewrite the files
    python3 desktop/tools/transcribe_golden.py --check     # fail if they moved

`--check` is what the desktop job runs: a change to the Python rules then fails
CI on the Rust test instead of silently drifting away from it.
"""

from __future__ import annotations

import importlib.util
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
GOLDEN = ROOT / "desktop" / "crates" / "nz-transcribe" / "tests" / "golden"

EPISODE = "6f0a4d3c-6b1e-4a4e-9d0e-2f0c9f6f1a11"
CREATED = "2026-11-16T09:01:00"
UPDATED = "2026-11-16T09:04:30"
MODEL = "ggml-large-v3-turbo-q8_0.bin"


def load(name: str, relative: str):
    """Import one file of the server by path, with no package around it."""
    path = ROOT / relative
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:  # pragma: no cover - a missing tree
        raise SystemExit(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


engine = load("nz_golden_engine", "neezer/transcribe/engine.py")
sidecar = load("nz_golden_sidecar", "neezer/transcribe/sidecar.py")


def line(text, start, end):
    """One raw whisper.cpp segment, as `-oj` writes it."""
    return {"offsets": {"from": start, "to": end}, "text": text}


def meta(language="fr", duration_ms=3_600_000, model=MODEL):
    return {
        "episode_id": EPISODE,
        "language": language,
        "engine": "whisper.cpp",
        "model": model,
        "engine_version": "1.9.5",
        "duration_ms": duration_ms,
        "created": CREATED,
        "updated": UPDATED,
    }


def cases():
    """Every case, in the order they are written. The script owns them: a new
    case is a new entry here, never a hand-edited file under `tests/golden/`."""
    out = []

    def case(name, items, start=0, duration=600_000, overlap=2_000,
             document=None, raw_segments=None):
        out.append(
            {
                "name": name,
                "items": items,
                "chunk_start_ms": start,
                "chunk_duration_ms": duration,
                "overlap_ms": overlap,
                "sidecar": document,
                "sidecar_segments": raw_segments,
            }
        )

    # 1. The ordinary first chunk: clean lines, a tag dropped, spacing collapsed.
    case(
        "01-first-chunk",
        [
            line("Bonjour à tous.", 0, 800),
            line("  on commence  ", 800, 2400),
            line("[Musique]", 2400, 9000),
            line("Une phrase   longue.", 9000, 12_000),
            line("fin.", 12_000, 12_600),
        ],
        document=meta(),
    )

    # 2. A resumed chunk: what the previous chunk already said is dropped, what
    #    straddles the cutoff is kept once, what is past the end is not ours.
    case(
        "02-overlap-cutoff",
        [
            line("dans l'overlap", 0, 1900),
            line("presque", 1999, 2000),
            line("à cheval", 2500, 5000),
            line("[Musique]", 5000, 9000),
            line("Une phrase.", 9000, 12_000),
            line("hors du chunk", 601_000, 602_000),
        ],
        start=600_000,
        duration=600_000,
        document=meta(duration_ms=1_200_000),
    )

    # 3. Clamping: a negative offset, a segment running past the chunk's end, one
    #    that starts exactly at it and clamps to nothing.
    case(
        "03-clamp-at-edges",
        [
            line("négatif", -5000, 5000),
            line("déborde", 598_000, 610_000),
            line("très long", 100_000, 900_000),
            line("pile sur la fin", 600_000, 700_000),
        ],
        start=600_000,
        duration=600_000,
        document=meta(duration_ms=1_200_000),
    )

    # 4. Chunk 0 has no previous chunk: its first words are the episode's first
    #    words, even though the overlap is set.
    case(
        "04-zero-chunk-keeps-the-head",
        [
            line("tête", 0, 500),
            line("encore la tête", 1500, 2500),
        ],
        duration=60_000,
        document=meta(duration_ms=60_000),
    )

    # 5. Only a whole line in brackets is a tag: the engine drops it, the sidecar
    #    would keep it (see 15).
    case(
        "05-tag-only",
        [
            line("[Musique]", 0, 1000),
            line("[]", 1000, 2000),
            line("[ Applaudissements ]", 2000, 3000),
            line("[a][b]", 3000, 4000),
            line("[rire] bonjour", 4000, 5000),
            line("Musique]", 5000, 6000),
            line("[", 6000, 7000),
        ],
        duration=60_000,
        document=meta(duration_ms=60_000),
    )

    # 6. Control characters become spaces; tabs, newlines and Unicode spaces are
    #    collapsed; a zero-width space is a character, not whitespace.
    case(
        "06-control-characters",
        [
            line("a\x00b", 0, 1000),
            line("c\x07d\x7f", 1000, 2000),
            line("e\x0bf\x0cg", 2000, 3000),
            line("h\x1fi", 3000, 4000),
            line("\u00a0j\u00a0k\u3000l", 4000, 5000),
            line("m\u200bn", 5000, 6000),
            line("\t\n\r", 6000, 7000),
        ],
        duration=60_000,
        document=meta(duration_ms=60_000),
    )

    # 7. Unicode survives as itself: accents, CJK, Arabic, an emoji with its
    #    variation selector, a decomposed accent.
    case(
        "07-unicode",
        [
            line("Français, épisode numéro un — « déjà vu ».", 0, 4000),
            line("日本語のポッドキャストです。", 4000, 8000),
            line("مرحبا بالعالم", 8000, 12_000),
            line("🎧🎙️ un micro", 12_000, 16_000),
            line("e\u0301 combining", 16_000, 20_000),
        ],
        duration=60_000,
        document=meta(duration_ms=60_000),
    )

    # 8. The 2 000-character ceiling, counted in characters: 2 500 ASCII is cut,
    #    2 000 accented characters are not, and whitespace collapses before the
    #    cut so 2 000 spaces in front of a word leave the word.
    case(
        "08-max-text",
        [
            line("x" * 2500, 0, 1000),
            line("é" * 2000, 1000, 2000),
            line("é" * 2001, 2000, 3000),
            line(" " * 2000 + "mot", 3000, 4000),
            line("a " * 1500, 4000, 5000),
        ],
        duration=60_000,
        document=meta(duration_ms=60_000),
    )

    # 9. Malformed entries are skipped, never fatal: non-objects, no offsets,
    #    offsets of the wrong type, an end at or before the start, and offsets
    #    that are absurd but clampable.
    case(
        "09-broken-offsets",
        [
            42,
            "texte",
            None,
            [1, 2],
            {"text": "sans offsets"},
            {"offsets": "nope", "text": "x"},
            {"offsets": {"from": "12", "to": 20}, "text": "x"},
            {"offsets": {"from": True, "to": 20}, "text": "x"},
            {"offsets": {"from": 10, "to": 10}, "text": "x"},
            {"offsets": {"from": 30, "to": 20}, "text": "x"},
            {"offsets": {"from": -1000, "to": 2000}, "text": "négatif"},
            {"offsets": {"from": 500_000, "to": 999_999_999}, "text": "très loin"},
            {"offsets": {"from": 100, "to": 200}, "text": "la seule"},
        ],
        duration=600_000,
        document=meta(),
    )

    # 10. Fractional offsets round HALF TO EVEN, as Python's `round` does: away
    #     from zero would move every second line by a millisecond.
    case(
        "10-half-millisecond-rounding",
        [
            line("a", 1500.5, 1501.5),
            line("b", 2500.5, 4000.5),
            line("c", 0.5, 1.5),
            line("d", 10.25, 20.75),
            line("e", 100.5, 100.5),
        ],
        duration=60_000,
        document=meta(duration_ms=60_000),
    )

    # 11. An episode nobody spoke in: zero lines, and zero bytes of subtitles —
    #     the difference between "no transcript" and "a transcript with no line".
    case("11-empty-chunk", [], duration=60_000, document=meta(duration_ms=60_000))

    # 12. The cap `job.py#apply_chunk` enforces: 2 001 lines in, 2 000 out. No
    #     document (it would be a 200 kB fixture for no extra rule).
    case(
        "12-two-thousand-and-one-segments",
        [line("a", i * 1000, i * 1000 + 900) for i in range(2001)],
    )

    # 13. Sorted by start then end, whatever order whisper wrote them in, and a
    #     repeated line is two lines.
    case(
        "13-sorted-by-start-then-end",
        [
            line("trois", 9000, 12_000),
            line("un bis", 3000, 4000),
            line("deux", 3000, 5000),
            line("trois bis", 9000, 12_000),
            line("un", 0, 3000),
        ],
        duration=60_000,
        document=meta(duration_ms=60_000),
    )

    # 14. A line that is only whitespace is not a line.
    case(
        "14-whitespace-only-text",
        [
            line(" ", 0, 1000),
            line("\t\n ", 1000, 2000),
            line("   \u00a0 ", 2000, 3000),
            line("\u3000\u3000", 3000, 4000),
            line("un mot", 4000, 5000),
            line("  un   mot  ", 5000, 6000),
        ],
        duration=60_000,
        document=meta(duration_ms=60_000),
    )

    # 15. A document built from lines the server already holds: the sidecar's own
    #     cleaning (control characters AND tabs become spaces, 2 000 characters)
    #     and its own sorting, which keeps a tag the engine would have dropped.
    case(
        "15-sidecar-cleaning",
        [],
        duration=60_000,
        document=meta(duration_ms=60_000),
        raw_segments=[
            {"start_ms": 5000, "end_ms": 6000, "text": "  déjà   vu  "},
            {"start_ms": 0, "end_ms": 1000, "text": "[Musique]"},
            {"start_ms": 1000, "end_ms": 2000, "text": "a\x01 b\tc\x7fd"},
            {"start_ms": 2000, "end_ms": 3000, "text": "z" * 2500},
        ],
    )

    # 16. A document nobody finished: every metadata field the server may not know
    #     yet is null on the wire, and a duration of 0 is 0.
    case(
        "16-null-metadata",
        [line("Une seule ligne.", 0, 2400)],
        duration=60_000,
        document={
            "episode_id": EPISODE,
            "language": None,
            "engine": "whisper.cpp",
            "model": None,
            "engine_version": None,
            "duration_ms": 0,
            "created": None,
            "updated": None,
        },
    )

    return out


def compact(value) -> bytes:
    """The bytes the Rust side must produce: compact, UTF-8, one newline."""
    return (json.dumps(value, ensure_ascii=False, separators=(",", ":")) + "\n").encode(
        "utf-8"
    )


def render() -> dict[pathlib.Path, bytes]:
    """Every file the golden directory must contain, and what is in it."""
    files: dict[pathlib.Path, bytes] = {}
    for case in cases():
        directory = GOLDEN / case["name"]
        items = case["items"]
        start = case["chunk_start_ms"]
        duration = case["chunk_duration_ms"]
        overlap = case["overlap_ms"]
        segments = engine.normalize_segments(items, start, duration, overlap_ms=overlap)
        files[directory / "segments.json"] = compact(segments)
        files[directory / "case.json"] = compact(
            {
                "items": items,
                "chunk_start_ms": start,
                "chunk_duration_ms": duration,
                "overlap_ms": overlap,
                "sidecar": case["sidecar"],
                "sidecar_segments": case["sidecar_segments"],
            }
        )
        document_meta = case["sidecar"]
        if document_meta is None:
            continue
        raw = case["sidecar_segments"]
        document = sidecar.build(
            episode_id=document_meta["episode_id"],
            language=document_meta["language"],
            engine=document_meta["engine"],
            model=document_meta["model"],
            engine_version=document_meta["engine_version"],
            duration_ms=document_meta["duration_ms"],
            segments=segments if raw is None else raw,
            created=document_meta["created"],
            updated=document_meta["updated"],
        )
        files[directory / "transcript.json"] = sidecar.dumps(document)
        files[directory / "transcript.srt"] = sidecar.srt_bytes(document["segments"])
    return files


def main(argv: list[str]) -> int:
    check = "--check" in argv
    unknown = [argument for argument in argv if argument not in ("--check", "-h", "--help")]
    if "-h" in argv or "--help" in argv:
        print(__doc__)
        return 0
    if unknown:
        print(f"argument inconnu : {' '.join(unknown)}", file=sys.stderr)
        return 2
    files = render()
    stale: list[str] = []
    written = 0
    for path, data in sorted(files.items()):
        relative = path.relative_to(ROOT)
        if check:
            try:
                current = path.read_bytes()
            except FileNotFoundError:
                stale.append(f"{relative} : absent")
                continue
            if current != data:
                stale.append(f"{relative} : différent de ce que Python produit")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        written += 1
    if check:
        for line in stale:
            print(line, file=sys.stderr)
        if stale:
            print(
                f"{len(stale)} fichier(s) périmé(s) ; "
                "lancez python3 desktop/tools/transcribe_golden.py",
                file=sys.stderr,
            )
            return 1
        print(f"{len(files)} fichiers à jour dans {GOLDEN.relative_to(ROOT)}")
        return 0
    total = sum(len(data) for data in files.values())
    print(
        f"{written} fichiers écrits dans {GOLDEN.relative_to(ROOT)} "
        f"({len(cases())} cas, {total} octets)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
